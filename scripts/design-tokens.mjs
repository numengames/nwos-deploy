// Design tokens → src/styles/tokens.css
//
// The source of every colour, radius and curve is the installed package
// @numengames/design-kit (numinia-nwos, packages/design-kit/). This script
// reads its token file and writes the CSS custom properties Tailwind consumes
// (RGB triplets, so `bg-bg/50` can apply opacity). Nothing here is typed by
// hand: STD-008 DSN-009 — the kit is installed, never copied.
//
//   node scripts/design-tokens.mjs           # write src/styles/tokens.css
//   node scripts/design-tokens.mjs --check   # exit 1 if the file is stale
//
// Runs as `predev`/`prebuild`, so a bumped package regenerates the file and a
// hand edit is overwritten on the next build.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const TOKENS = require.resolve("@numengames/design-kit/sistema.tokens.json");
const PKG = JSON.parse(fs.readFileSync(path.join(path.dirname(TOKENS), "package.json"), "utf8"));
const OUT = path.resolve("src/styles/tokens.css");
const CHECK = process.argv.includes("--check");

const t = JSON.parse(fs.readFileSync(TOKENS, "utf8"));
const get = (p) => {
	const node = p.split(".").reduce((o, k) => (o == null ? undefined : o[k]), t);
	if (node == null || node.$value === undefined) throw new Error(`token missing: ${p}`);
	return node.$value;
};
const rgb = (hex) => {
	const h = hex.replace("#", "");
	return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
};

/* CSS variable ← token path. The left side is this repo's vocabulary
   (Tailwind config); the right side is the kit's. Aliases stay aliases. */
const COLORS = {
	"--bg": "color.nocturno.fondo-base",
	"--bg-card": "color.nocturno.fondo-superficie",
	"--bg-card-hover": "color.nocturno.fondo-elevada",
	"--border": "color.nocturno.linea-fuerte",
	"--border-soft": "color.nocturno.linea-tenue",
	"--text": "color.nocturno.texto-primario",
	"--text-muted": "color.nocturno.texto-secundario",
	"--text-dim": "color.nocturno.texto-terciario",
	"--accent": "color.enlace.nocturno",
	"--interactivo": "color.interactivo.fondo",
	"--interactivo-hover": "color.interactivo.hover",
	"--interactivo-activo": "color.interactivo.activo",
	"--verdemar": "color.marca.verdemar",
	"--turquesa": "color.marca.turquesa",
	"--ambar": "color.marca.ambar",
	"--arena": "color.marca.arena",
	"--coral": "color.marca.coral",
	"--grana": "color.marca.grana",
	// Inherited flavour names: each holds the token that occupies its role.
	"--terracota": "color.marca.ambar",
	"--ocre": "color.marca.ambar",
	"--cobre": "color.marca.ambar",
	"--bronce": "color.nocturno.texto-terciario",
	"--teal": "color.marca.turquesa",
};
/* --blue and --purple were copied from the rarity scale (raro, épico). STD-023
   says rarity never colours data; they keep their value so nothing breaks, but
   any use of them as a data colour is a breach to fix here, not in the kit. */
const DATA_VARS = {
	"--green": "color.rareza.poco-comun",
	"--red": "color.marca.grana",
	"--yellow": "color.marca.ambar",
	"--blue": "color.rareza.raro",
	"--purple": "color.rareza.epico",
	"--salvia": "color.rareza.poco-comun",
	"--azul-med": "color.rareza.raro",
};

let css = `/* SPDX-FileCopyrightText: 2026 Numen Games S.L. */
/* SPDX-License-Identifier: AGPL-3.0-only */
/* GENERATED by scripts/design-tokens.mjs from @numengames/design-kit ${PKG.version}.
 * Do not edit: the source is packages/design-kit/ in numinia-nwos (ADR-044).
 * Registro Umbral · modo Nocturno. RGB triplets so Tailwind can apply opacity. */
:root {
`;
for (const [v, p] of Object.entries(COLORS)) css += `\t${v}: ${rgb(get(p))}; /* ${get(p)} */\n`;
css += `\n\t/* Data and inherited flavour names */\n`;
for (const [v, p] of Object.entries(DATA_VARS)) css += `\t${v}: ${rgb(get(p))}; /* ${get(p)} */\n`;
css += `\n\t/* Atmósfera del Velo · solo alfa sobre canónicos */\n`;
css += `\t--accent-glow: rgba(${rgb(get("color.marca.turquesa")).replaceAll(" ", ", ")}, 0.08);\n`;
css += `\t--veil-glow: rgba(${rgb(get("color.marca.turquesa")).replaceAll(" ", ", ")}, 0.06);\n`;
css += `\t--cobre-glow: rgba(${rgb(get("color.marca.ambar")).replaceAll(" ", ", ")}, 0.18);\n`;
css += `\n\t/* Escala de rareza (color.rareza) · nunca colorea datos */\n`;
for (const k of ["comun", "poco-comun", "raro", "epico", "legendario"]) css += `\t--rareza-${k}: ${rgb(get(`color.rareza.${k}`))}; /* ${get(`color.rareza.${k}`)} */\n`;
css += `\n\t/* Forma · dos radios y solo dos */\n`;
css += `\t--radius: ${get("borderRadius.marco")};\n\t--radius-control: ${get("borderRadius.control")};\n`;
const cb = get("cubicBezier.ciclo");
css += `\t--ciclo: cubic-bezier(${Array.isArray(cb) ? cb.join(", ") : cb});\n}\n`;

/* Modo Diurno (STD-008 DSN-016): the same variable names, re-pointed at the
   kit's day values when <html data-modo="diurno">; absent = Nocturno above.
   Accents that are mood colours over the night become their text-over-light
   variants by day (STD-023: Turquesa, Ámbar, Grana, Verdemar); Coral has no
   variant by decision, so a coral message is written in Grana-text. */
const ext = (p) => {
	const node = p.split(".").reduce((o, k) => (o == null ? undefined : o[k]), t);
	const v = node?.$extensions?.numen?.diurnoTexto;
	if (!v) throw new Error(`day text variant missing: ${p}`);
	return v;
};
const DIURNO = {
	"--bg": () => get("color.diurno.fondo-base"),
	"--bg-card": () => get("color.diurno.fondo-superficie"),
	"--bg-card-hover": () => get("color.diurno.linea-tenue"),
	"--border": () => get("color.nocturno.texto-secundario"),
	"--border-soft": () => get("color.diurno.linea-tenue"),
	"--text": () => get("color.diurno.texto-primario"),
	"--text-muted": () => get("color.diurno.texto-secundario"),
	"--text-dim": () => get("color.diurno.texto-terciario"),
	"--accent": () => get("color.enlace.diurno"),
	"--verdemar": () => get("color.texto-sobre-claro.verdemar"),
	"--ambar": () => get("color.texto-sobre-claro.ambar"),
	"--coral": () => get("color.texto-sobre-claro.grana"),
	"--terracota": () => get("color.texto-sobre-claro.ambar"),
	"--ocre": () => get("color.texto-sobre-claro.ambar"),
	"--cobre": () => get("color.texto-sobre-claro.ambar"),
	"--bronce": () => get("color.diurno.texto-terciario"),
	"--green": () => ext("color.rareza.poco-comun"),
	"--red": () => get("color.texto-sobre-claro.grana"),
	"--yellow": () => get("color.texto-sobre-claro.ambar"),
	"--blue": () => ext("color.rareza.raro"),
	"--purple": () => ext("color.rareza.epico"),
	"--salvia": () => ext("color.rareza.poco-comun"),
	"--azul-med": () => ext("color.rareza.raro"),
	"--rareza-comun": () => ext("color.rareza.comun"),
	"--rareza-poco-comun": () => ext("color.rareza.poco-comun"),
	"--rareza-raro": () => ext("color.rareza.raro"),
	"--rareza-epico": () => ext("color.rareza.epico"),
	"--rareza-legendario": () => ext("color.rareza.legendario"),
};
css += `\n/* Modo Diurno · data-modo="diurno" on <html>; absent = Nocturno. */\n[data-modo="diurno"] {\n`;
for (const [v, f] of Object.entries(DIURNO)) css += `\t${v}: ${rgb(f())}; /* ${f()} */\n`;
css += `}\n`;

if (CHECK) {
	const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
	if (cur !== css) {
		console.error(`design-tokens: ${path.relative(".", OUT)} is stale — run node scripts/design-tokens.mjs`);
		process.exit(1);
	}
	console.log(`design-tokens: ${path.relative(".", OUT)} matches @numengames/design-kit ${PKG.version}.`);
} else {
	fs.writeFileSync(OUT, css);
	console.log(`design-tokens: wrote ${path.relative(".", OUT)} from @numengames/design-kit ${PKG.version}.`);
}
